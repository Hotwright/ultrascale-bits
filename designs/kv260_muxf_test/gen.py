#!/usr/bin/env python3
"""Generate muxlab.v (96 wide-mux trees with random LUT contents) and
expected.tcl (the three output words for each of the 512 input values).
Semantics as Vivado: MUXFn O = S ? I1 : I0; LUT6 O = INIT[{I5..I0}]."""
import random
random.seed(20261101)
N = 32
def lut(): return random.getrandbits(64)
f9 = [[lut() for _ in range(8)] for _ in range(N)]
f8 = [[lut() for _ in range(4)] for _ in range(N)]
f7 = [[lut() for _ in range(2)] for _ in range(N)]
v = ["// GENERATED by gen.py: 32 F9 trees, 32 F8 trees, 32 F7 trees.",
     "module muxlab(input [8:0] x, output [31:0] o9, output [31:0] o8, output [31:0] o7);",
     "  wire [5:0] a = x[5:0]; wire s7 = x[6], s8 = x[7], s9 = x[8];"]
def L(name, init, out):
    return ("  (* DONT_TOUCH = \"yes\" *) LUT6 #(.INIT(64'h%016x)) %s (.I0(a[0]),.I1(a[1]),.I2(a[2]),"
            ".I3(a[3]),.I4(a[4]),.I5(a[5]),.O(%s));" % (init, name, out))
def M(kind, name, i0, i1, s, o):
    return "  (* DONT_TOUCH = \"yes\" *) %s %s (.I0(%s),.I1(%s),.S(%s),.O(%s));" % (kind, name, i0, i1, s, o)
for t in range(N):
    p = "t9_%d" % t
    v.append("  wire [7:0] %s_l; wire [3:0] %s_7; wire [1:0] %s_8;" % (p, p, p))
    for k in range(8): v.append(L("%s_lut%d" % (p, k), f9[t][k], "%s_l[%d]" % (p, k)))
    for k in range(4): v.append(M("MUXF7", "%s_m7_%d" % (p, k), "%s_l[%d]" % (p, 2*k), "%s_l[%d]" % (p, 2*k+1), "s7", "%s_7[%d]" % (p, k)))
    for k in range(2): v.append(M("MUXF8", "%s_m8_%d" % (p, k), "%s_7[%d]" % (p, 2*k), "%s_7[%d]" % (p, 2*k+1), "s8", "%s_8[%d]" % (p, k)))
    v.append(M("MUXF9", "%s_m9" % p, "%s_8[0]" % p, "%s_8[1]" % p, "s9", "o9[%d]" % t))
    p = "t8_%d" % t
    v.append("  wire [3:0] %s_l; wire [1:0] %s_7;" % (p, p))
    for k in range(4): v.append(L("%s_lut%d" % (p, k), f8[t][k], "%s_l[%d]" % (p, k)))
    for k in range(2): v.append(M("MUXF7", "%s_m7_%d" % (p, k), "%s_l[%d]" % (p, 2*k), "%s_l[%d]" % (p, 2*k+1), "s7", "%s_7[%d]" % (p, k)))
    v.append(M("MUXF8", "%s_m8" % p, "%s_7[0]" % p, "%s_7[1]" % p, "s8", "o8[%d]" % t))
    p = "t7_%d" % t
    v.append("  wire [1:0] %s_l;" % p)
    for k in range(2): v.append(L("%s_lut%d" % (p, k), f7[t][k], "%s_l[%d]" % (p, k)))
    v.append(M("MUXF7", "%s_m7" % p, "%s_l[0]" % p, "%s_l[1]" % p, "s7", "o7[%d]" % t))
v.append("endmodule")
open("muxlab.v", "w").write("\n".join(v) + "\n")
def bit(init, a): return (init >> a) & 1
def ev7(l, a, s7): return bit(l[1], a) if s7 else bit(l[0], a)
exp = []
for x in range(512):
    a, s7, s8, s9 = x & 63, (x >> 6) & 1, (x >> 7) & 1, (x >> 8) & 1
    w9 = w8 = w7 = 0
    for t in range(N):
        m7 = [ev7(f9[t][2*k:2*k+2], a, s7) for k in range(4)]
        m8 = [m7[1] if s8 else m7[0], m7[3] if s8 else m7[2]]
        w9 |= (m8[1] if s9 else m8[0]) << t
        n7 = [ev7(f8[t][2*k:2*k+2], a, s7) for k in range(2)]
        w8 |= (n7[1] if s8 else n7[0]) << t
        w7 |= ev7(f7[t], a, s7) << t
    exp.append("{0x%08x 0x%08x 0x%08x}" % (w9, w8, w7))
open("expected.tcl", "w").write("set EXP {\n" + "\n".join(exp) + "\n}\n")
