#!/usr/bin/env python3
"""Write spec.v: BRAM primitives with random contents, for a bit-for-bit
comparison of our BRAM tiles against Vivado's.

Every BRAM is instantiated directly, with every parameter that matters spelled
out, and LOC'd to a fixed site in both XDCs, so both tools must produce the
same tile. Nothing here is meant to do anything useful on the board: the LEDs
are an XOR of the outputs only so that neither tool can trim a BRAM away.
"""
import random

random.seed(20261024)


def hexstr(bits):
    return "%d'h%0*X" % (bits, bits // 4, random.getrandbits(bits))


def inits(n_init, n_initp):
    out = []
    for i in range(n_init):
        out.append(".INIT_%02X(%s)" % (i, hexstr(256)))
    for i in range(n_initp):
        out.append(".INITP_%02X(%s)" % (i, hexstr(256)))
    return out


def ram(kind, name, params, ports):
    n_init, n_initp = (64, 8) if kind == "RAMB18E2" else (128, 16)
    ps = params + inits(n_init, n_initp)
    s = "    (* keep *) %s #(\n        %s\n    ) %s (\n        %s\n    );\n" % (
        kind, ",\n        ".join(ps), name, ",\n        ".join(ports))
    return s


body = []
# RAMB18 lower half, 9 bit read, no output register.
body.append(ram("RAMB18E2", "r18l", [
    ".READ_WIDTH_A(9)", ".WRITE_WIDTH_A(9)", ".READ_WIDTH_B(9)", ".WRITE_WIDTH_B(9)",
    ".DOA_REG(0)", ".DOB_REG(0)", ".INIT_A(18'h%05X)" % random.getrandbits(18),
    ".SRVAL_A(18'h%05X)" % random.getrandbits(18)],
    [".CLKARDCLK(clk)", ".ENARDEN(1'b1)", ".ADDRARDADDR({ctr[25:15], 3'b000})",
     ".WEA(2'b00)", ".DOUTADOUT(d18l)", ".DOUTPADOUTP(p18l)"]))
# RAMB18 upper half, 18 bit read, output register.
body.append(ram("RAMB18E2", "r18u", [
    ".READ_WIDTH_A(18)", ".WRITE_WIDTH_A(18)", ".READ_WIDTH_B(4)", ".WRITE_WIDTH_B(4)",
    ".DOA_REG(1)", ".DOB_REG(0)"],
    [".CLKARDCLK(clk)", ".CLKBWRCLK(clk)", ".ENARDEN(1'b1)", ".ENBWREN(1'b1)",
     ".REGCEAREGCE(1'b1)", ".ADDRARDADDR({ctr[24:15], 4'b0000})",
     ".ADDRBWRADDR({ctr[26:15], 2'b00})", ".WEA(2'b00)", ".WEBWE(4'b0000)",
     ".DOUTADOUT(d18u)", ".DOUTPADOUTP(p18u)", ".DOUTBDOUT(d18ub)"]))
# RAMB36, 36 bit read.
body.append(ram("RAMB36E2", "r36", [
    ".READ_WIDTH_A(36)", ".WRITE_WIDTH_A(36)", ".READ_WIDTH_B(36)", ".WRITE_WIDTH_B(36)",
    ".DOA_REG(0)", ".DOB_REG(0)"],
    [".CLKARDCLK(clk)", ".ENARDEN(1'b1)", ".ADDRARDADDR({ctr[24:15], 5'b00000})",
     ".WEA(4'b0000)", ".DOUTADOUT(d36)", ".DOUTPADOUTP(p36)"]))
# RAMB36, 9 bit read on A, 2 bit on B.
body.append(ram("RAMB36E2", "r36n", [
    ".READ_WIDTH_A(9)", ".WRITE_WIDTH_A(9)", ".READ_WIDTH_B(2)", ".WRITE_WIDTH_B(2)",
    ".DOA_REG(0)", ".DOB_REG(0)"],
    [".CLKARDCLK(clk)", ".CLKBWRCLK(clk)", ".ENARDEN(1'b1)", ".ENBWREN(1'b1)",
     ".ADDRARDADDR(ctr[26:12])", ".ADDRBWRADDR(ctr[25:11])",
     ".WEA(4'b0000)", ".WEBWE(8'h00)", ".DOUTADOUT(d36n)", ".DOUTPADOUTP(p36n)",
     ".DOUTBDOUT(d36nb)"]))

src = """// Generated by gen_spec.py -- see there.
module top (output wire [7:0] pmod);
    wire [3:0] plclk;
    PS8 ps8_i (.PLCLK(plclk));
    wire clk;
    BUFG_PS bufg_i (.I(plclk[0]), .O(clk));
    reg [26:0] ctr = 27'd0;
    always @(posedge clk) ctr <= ctr + 1'b1;

    wire [15:0] d18l, d18u, d18ub;
    wire [1:0] p18l, p18u;
    wire [31:0] d36, d36n, d36nb;
    wire [3:0] p36, p36n;

%s
    wire [7:0] a = d18l[7:0] ^ {p18l[0], d18u[15:9]} ^ d18u[7:0] ^ {p18u, d18ub[3:0], d18l[8], p18l[1]};
    wire [7:0] b = d36[7:0] ^ d36[15:8] ^ d36[23:16] ^ d36[31:24] ^ {p36, d36n[3:0]};
    wire [7:0] c = {d36n[7:4], p36n[0], d36nb[1:0], 1'b0};
    reg [7:0] q;
    always @(posedge clk) q <= a ^ b ^ c;
    assign pmod = q;
endmodule
""" % "\n".join(body)
open("spec.v", "w").write(src)
