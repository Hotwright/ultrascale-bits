#!/usr/bin/env python3
"""Write nextpnr's usp_uram_rows.h from out_rows.txt: which INT row (and
side) each URAM288 output pin leaves its tile on, per site position.

    gen_rows_h.py out_rows.txt > .../himbaechel/uarch/xilinx/usp_uram_rows.h
"""
import sys

rows = []
for line in open(sys.argv[1]):
    if line.strip() and not line.startswith("#"):
        y, pin, side, row = line.split()
        rows.append((int(y), pin, side, int(row)))
print("// Generated by 0-ultrascale-bits designs/kv260_uram_char/gen_rows_h.py from")
print("// out_rows.txt: the INT row a URAM288 output pin leaves its tile on, per")
print("// site position in the tile. A used output sets OUT_<side>_ROW<row>.")
print("#pragma once")
print("struct UspUramRow\n{\n    int site;\n    const char *pin;\n    char side;\n    int row;\n};")
print("static const UspUramRow usp_uram_rows[] = {")
for y, pin, side, row in rows:
    print('        {%d, "%s", \'%s\', %d},' % (y, pin, side, row))
print("};")
