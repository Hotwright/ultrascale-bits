#!/usr/bin/env python3
"""Write nextpnr's usp_dsp_rows.h from out_rows.txt: which INT row each
DSP48E2 output site pin leaves its tile on, per site position.

    gen_rows_h.py out_rows.txt > .../himbaechel/uarch/xilinx/usp_dsp_rows.h
"""
import sys

print("// Generated by 0-ultrascale-bits designs/kv260_dsp_char/gen_rows_h.py from")
print("// out_rows.txt: the INT row a DSP48E2 output pin leaves its tile on, per")
print("// site position in the tile. A used output sets OUT_ROW<row>.")
print("#pragma once")
print("struct UspDspRow\n{\n    int site;\n    const char *pin;\n    int row;\n};")
print("static const UspDspRow usp_dsp_rows[] = {")
for line in open(sys.argv[1]):
    if line.strip() and not line.startswith("#"):
        y, pin, row = line.split()
        print('        {%s, "%s", %s},' % (y, pin, row))
print("};")
