#!/usr/bin/env python3
"""Write nextpnr's usp_cmt_l_pips.h: every CMT_L pip that has bits.

XilinxImpl::init blocks every other CMT_L pip, so the router can only build
a clock route the FASM can express. The exceptions it adds itself are the
bitless pips known to work on the board (SCOPE-K26.md): BUFGCE_DIV
CLK_IN_PIN, and MUX_2TO1 <- HROUTE_0_t, whose bit is carried by
WIRE.CLK_HROUTE_0_t.USED (the routes the overlay gives that feature).

    tools/gen_cmt_l_pips.py > ../eda-tools/nextpnr/himbaechel/uarch/xilinx/usp_cmt_l_pips.h

Reads the overlay segbits (run mk_uray_overlay.sh first).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.join(HERE, "..", "prjuray", "database", "zynqusp", "segbits_cmt_l.db")

pips, wires = set(), set()
for line in open(DB):
    f = line.split()[0] if line.strip() else ""
    if f.startswith("CMT_L.PIP."):
        pips.add(f[len("CMT_L.PIP."):])
    elif f.startswith("CMT_L.WIRE.") and f.endswith(".USED.V1"):
        wires.add(f[len("CMT_L.WIRE."):-len(".USED.V1")])

print("// Generated by 0-ultrascale-bits/tools/gen_cmt_l_pips.py from the overlay")
print("// segbits_cmt_l.db: every CMT_L pip with bits, as \"<dst>.<src>\", and every")
print("// CMT_L wire with a USED bit. Do not edit.")
print("#ifndef USP_CMT_L_PIPS_H")
print("#define USP_CMT_L_PIPS_H")
print("namespace UspCmtL {")
print("static const char *const pips[] = {")
for p in sorted(pips):
    print('        "%s",' % p)
print("};")
print("static const char *const used_wires[] = {")
for w in sorted(wires):
    print('        "%s",' % w)
print("};")
print("} // namespace UspCmtL")
print("#endif")
